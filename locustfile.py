class FastAPIUser(HttpUser):
    wait_time = between(1, 2)

    @task(3)
    def test_predict(self):
        payload = {"text": random.choice(SAMPLE_TEXTS)}
        self.client.post("/predict", json=payload)

    @task(1)
    def test_health(self):
        self.client.get("/health")


